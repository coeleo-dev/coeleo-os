def render_features(content, shared, locale):
    t = content["i18n"][locale["code"]]
    groups = []
    for group in shared["features"]:
        group_copy = t["features"]["groups"][group["id"]]
        cards = []
        for card in group["cards"]:
            card_copy = group_copy["cards"][card]
            cards.append("\n".join([
                '        <article class="card">',
                '          <h3>%s</h3>' % card_copy["title"],
                '          <p>%s</p>' % card_copy["body"],
                '        </article>',
            ]))
        groups.append("\n".join([
            '    <div class="fgroup">',
            '      <h3 class="fgroup__title"><span>%s</span> %s</h3>' % (group["num"], group_copy["title"]),
            '      <div class="cards">',
            "\n".join(cards),
            '      </div>',
            '    </div>',
        ]))

    return "\n".join([
        '<section class="section" id="features">',
        '  <div class="wrap">',
        '    <h2 class="section__title">%s</h2>' % t["features"]["title"],
        '    <p class="section__lead">%s</p>' % t["features"]["lead"],
        "",
        "\n\n".join(groups),
        '  </div>',
        '</section>',
    ])


def render_screenshots(content, shared, locale):
    t = content["i18n"][locale["code"]]
    prefix = asset_prefix(locale)
    figures = []
    for index, shot in enumerate(shared["shots"], start=1):
        alt = t["screenshots"]["shots"][shot["id"]]
        label = "%s %d" % (t["screenshots"]["enlarge"], index)
        figures.append(
            '      <figure class="shot"><button type="button" aria-label="%s">'
            '<img src="%sassets/img/shots/%s" alt="%s" width="%d" height="%d" loading="lazy" decoding="async">'
            '</button></figure>'
            % (esc(label), prefix, shot["file"], esc(alt), shot["w"], shot["h"])
        )
    return "\n".join([
        '<section class="section section--alt" id="screenshots">',
        '  <div class="wrap">',
        '    <h2 class="section__title">%s</h2>' % t["screenshots"]["title"],
        '    <p class="section__lead">%s</p>' % t["screenshots"]["lead"],
        "",
        '    <div class="gallery" id="gallery">',
        "\n".join(figures),
        '    </div>',
        '  </div>',
        '</section>',
    ])


