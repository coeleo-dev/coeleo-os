def render_sitemap(content, shared):
    site = content["site"]
    alternates = "\n".join(
        '    <xhtml:link rel="alternate" hreflang="%s" href="%s"/>'
        % (candidate["hreflang"], page_url(site, candidate))
        for candidate in site["locales"]
    ) + '\n    <xhtml:link rel="alternate" hreflang="x-default" href="%s"/>' % page_url(
        site, site["locales"][0])

    urls = []
    for locale in site["locales"]:
        t = content["i18n"][locale["code"]]
        images = "\n".join(
            "    <image:image>\n      <image:loc>%sassets/img/shots/%s</image:loc>\n      <image:title>%s</image:title>\n    </image:image>"
            % (site["baseUrl"], shot["file"], esc(t["screenshots"]["shots"][shot["id"]]))
            for shot in shared["shots"]
        )
        urls.append("\n".join([
            "  <url>",
            "    <loc>%s</loc>" % page_url(site, locale),
            alternates,
            images,
            "  </url>",
        ]))

    return "\n".join([
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- %s -->" % HEADER,
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
        '        xmlns:xhtml="http://www.w3.org/1999/xhtml"',
        '        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">',
        "\n".join(urls),
        "</urlset>",
        "",
    ])


def render_llms(content):
    """llms.txt: the curated index. English only - the convention is English and
    this file is consumed by machines, which link out to the localised pages."""
    site = content["site"]
    en = content["i18n"]["en"]
    llms = en["llms"]

    sections = []
    for section in llms["sections"]:
        lines = "\n".join("- %s" % line for line in section["lines"])
        sections.append("## %s\n\n%s" % (section["title"], lines))

    links = "\n".join([
        "- [Website](%s): project overview, screenshots and roadmap." % site["baseUrl"],
        "- [Portuguese (pt-BR)](%spt/): the same site in Brazilian Portuguese." % site["baseUrl"],
        "- [Source code](%s): the kernel, userspace and the design system." % site["repoUrl"],
        "- [Architecture](%s/blob/main/docs/contrib/architecture.md): technical map of the code." % site["repoUrl"],
        "- [Development guide](%s/blob/main/docs/contrib/develop.md): build, test and debug workflows." % site["repoUrl"],
        "- [Contributor index](%s/blob/main/docs/contrib/README.md): start here." % site["repoUrl"],
    ])

    return "\n".join([
        "# %s" % site["brand"],
        "",
        "> %s" % llms["summary"],
        "",
        "\n\n".join(sections),
        "",
        "## Links",
        "",
        links,
        "",
        "<!-- %s -->" % HEADER,
        "",
    ])


def render_llms_full(content, shared):
    """llms-full.txt: everything a model needs in a single fetch."""
    site = content["site"]
    en = content["i18n"]["en"]
    llms = en["llms"]

    chunks = [
        "# %s — full reference" % site["brand"],
        "",
        "> %s" % llms["summary"],
        "",
    ]

    for section in llms["sections"]:
        chunks.append("## %s" % section["title"])
        chunks.append("")
        chunks.extend("- %s" % line for line in section["lines"])
        chunks.append("")

    chunks.append("## Implemented features")
    chunks.append("")
    for group in shared["features"]:
        group_copy = en["features"]["groups"][group["id"]]
        chunks.append("### %s" % strip_tags(group_copy["title"]))
        chunks.append("")
        for card in group["cards"]:
            card_copy = group_copy["cards"][card]
            chunks.append("- %s: %s" % (strip_tags(card_copy["title"]), strip_tags(card_copy["body"])))
        chunks.append("")

    chunks.append("## Kernel domains")
    chunks.append("")
    for domain in shared["domains"]:
        copy = en["architecture"]["domains"][domain["id"]]
        chunks.append("- %s (%s): %s" % (copy["name"], domain["folder"], copy["role"]))
    chunks.append("")

    chunks.append("## Userspace applications")
    chunks.append("")
    for item in shared["apps"]:
        chunks.append("- %s: %s" % (item["code"], strip_tags(en["apps"]["roles"][item["id"]])))
    chunks.append("")

    chunks.append("## Shared libraries")
    chunks.append("")
    for item in shared["libs"]:
        chunks.append("- %s: %s" % (item["code"], strip_tags(en["apps"]["libRoles"][item["id"]])))
    chunks.append("")

    chunks.append("## Roadmap")
    chunks.append("")
    for band in shared["roadmap"]:
        band_copy = en["roadmap"]["bands"][band["id"]]
        chunks.append("### %s (%s)" % (strip_tags(band_copy["title"]), en["roadmap"]["pills"][band["pill"]]))
        chunks.append("")
        chunks.append(strip_tags(band_copy["desc"]))
        chunks.append("")
        for phase in band["phases"]:
            phase_copy = band_copy["phases"][phase]
            chunks.append("- Phase %s, %s: %s" % (phase, strip_tags(phase_copy["title"]), strip_tags(phase_copy["body"])))
        chunks.append("")

    chunks.append("## Frequently asked questions")
    chunks.append("")
    for entry in en["faq"]["items"]:
        chunks.append("### %s" % entry["q"])
        chunks.append("")
        chunks.append(entry["a"])
        chunks.append("")

    chunks.append("## Links")
    chunks.append("")
    chunks.append("- Website: %s" % site["baseUrl"])
    chunks.append("- Source: %s" % site["repoUrl"])
    chunks.append("- Architecture: %s/blob/main/docs/contrib/architecture.md" % site["repoUrl"])
    chunks.append("- Development guide: %s/blob/main/docs/contrib/develop.md" % site["repoUrl"])
    chunks.append("")
    chunks.append("<!-- %s -->" % HEADER)
    chunks.append("")

    return "\n".join(chunks)


def strip_tags(value):
    text = re.sub(r"<[^>]+>", "", value)
    return html.unescape(text).replace("\u00a0", " ").strip()


