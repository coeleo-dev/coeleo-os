def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("wrote %s (%d bytes)" % (os.path.relpath(path, REPO_ROOT), len(text.encode("utf-8"))))


def relative_targets(html_text):
    """Every href/src that points inside the site (fragments and absolutes aside)."""
    targets = []
    for match in re.finditer(r'(?:href|src)="([^"#]+)"', html_text):
        target = match.group(1)
        if target.startswith(("http://", "https://", "//", "mailto:", "data:")):
            continue
        targets.append(target)
    return targets


def main():
    content = load_content()
    shared = content["shared"]
    validate(content, shared)

    outputs = {}
    for locale in content["site"]["locales"]:
        page = render_page(content, shared, locale)
        directory = os.path.join(SITE_DIR, locale["dir"]) if locale["dir"] else SITE_DIR
        outputs[os.path.join(directory, "index.html")] = page

    outputs[os.path.join(SITE_DIR, "sitemap.xml")] = render_sitemap(content, shared)
    outputs[os.path.join(SITE_DIR, "llms.txt")] = render_llms(content)
    outputs[os.path.join(SITE_DIR, "llms-full.txt")] = render_llms_full(content, shared)

    for path in sorted(outputs):
        write(path, outputs[path])

    # Sanity check after writing, so directory targets (pt/) resolve: a relative
    # link that lands on nothing is a 404 we would only catch in production.
    for path in sorted(outputs):
        if not path.endswith(".html"):
            continue
        base = os.path.dirname(path)
        for target in relative_targets(outputs[path]):
            resolved = os.path.normpath(os.path.join(base, target))
            if not os.path.exists(resolved):
                raise SystemExit("broken relative link in %s: %s"
                                 % (os.path.relpath(path, REPO_ROOT), target))
    print("relative links ok")


if __name__ == "__main__":
    main()
