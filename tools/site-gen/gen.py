#!/usr/bin/env python3
"""
Generate the Coeleo OS site from a single source of truth.

Input
-----
content.json — site facts, shared (non-translatable) structure, and the copy for
every locale.

Output (all committed; the Pages workflow uploads site/ as-is, so there is no
build step in CI):
  site/index.html
  site/pt/index.html
  site/sitemap.xml
  site/llms.txt
  site/llms-full.txt

site/robots.txt and site/404.html stay hand-written: they change rarely and
generating them would add churn for no gain.

Copy that lives in `i18n` is emitted as trusted HTML, so it may contain <code>,
<kbd>, <strong> and entities. Values used in attributes (title, alt, meta
content) and the FAQ answers are escaped instead, which is why they must stay
plain text. Every generated file carries a "do not edit" header.

Run: python3 tools/site-gen/gen.py
"""

import html
import json
import os
import re
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(SCRIPT_DIR))
SITE_DIR = os.path.join(REPO_ROOT, "site")
CONTENT = os.path.join(SCRIPT_DIR, "content.json")

GENERATED_BY = "tools/site-gen/gen.py"
HEADER = "Generated by %s from tools/site-gen/content.json. Do not edit by hand." % GENERATED_BY

DOMAIN_COL_WIDTH = 34
DIAGRAM_BOX_LEFT = 16
DIAGRAM_BOX_INNER = 21


def esc(value):
    """Escape a plain-text value for an HTML text node or attribute."""
    return html.escape(str(value), quote=True)


def load_content():
    with open(CONTENT, encoding="utf-8") as handle:
        return json.load(handle)


# --------------------------------------------------------------------------
# Validation: fail loudly instead of shipping a page with a missing string.
# --------------------------------------------------------------------------

_bilingual_cache = {}


def _bilingual_keys(value, path, out):
    """Collect the keys of a {locale: text} shaped subtree."""
    if isinstance(value, dict):
        for key, child in value.items():
            _bilingual_keys(child, "%s.%s" % (path, key), out)
    else:
        out[path] = value


def translated(i18n, locale, path):
    """Fetch `path` for `locale`, caching the flattened locale tree."""
    cache_key = locale
    if cache_key not in _bilingual_cache:
        flat = {}
        _bilingual_keys(i18n[locale], locale, flat)
        _bilingual_cache[cache_key] = flat
    full = "%s.%s" % (locale, path)
    if full not in _bilingual_cache[cache_key]:
        raise SystemExit("content.json: missing translation %r" % full)
    return _bilingual_cache[cache_key][full]


def require(condition, message):
    if not condition:
        raise SystemExit("content.json: %s" % message)


def validate(content, shared):
    locales = [loc["code"] for loc in content["site"]["locales"]]
    i18n = content["i18n"]
    require(sorted(i18n) == sorted(locales), "i18n locales must match site.locales")

    for locale in locales:
        for key in ("meta", "nav", "lightbox", "hero", "reuse", "features", "screenshots",
                    "architecture", "apps", "build", "roadmap", "docs", "faq", "footer"):
            require(key in i18n[locale], "i18n.%s is missing %r" % (locale, key))

        for group in shared["features"]:
            translated(i18n, locale, "features.groups.%s.title" % group["id"])
            for card in group["cards"]:
                translated(i18n, locale, "features.groups.%s.cards.%s.title" % (group["id"], card))
                translated(i18n, locale, "features.groups.%s.cards.%s.body" % (group["id"], card))

        for item in shared["reuse"]:
            translated(i18n, locale, "reuse.items.%s" % item["id"])
        for domain in shared["domains"]:
            translated(i18n, locale, "architecture.domains.%s.name" % domain["id"])
            translated(i18n, locale, "architecture.domains.%s.role" % domain["id"])
        for app in shared["apps"]:
            translated(i18n, locale, "apps.roles.%s" % app["id"])
        for lib in shared["libs"]:
            translated(i18n, locale, "apps.libRoles.%s" % lib["id"])
        for shot in shared["shots"]:
            translated(i18n, locale, "screenshots.shots.%s" % shot["id"])
        for band in shared["roadmap"]:
            translated(i18n, locale, "roadmap.bands.%s.title" % band["id"])
            translated(i18n, locale, "roadmap.bands.%s.desc" % band["id"])
            for phase in band["phases"]:
                translated(i18n, locale, "roadmap.bands.%s.phases.%s.title" % (band["id"], phase))
                translated(i18n, locale, "roadmap.bands.%s.phases.%s.body" % (band["id"], phase))
        for doc in shared["docs"]:
            translated(i18n, locale, "docs.items.%s.label" % doc["id"])
            translated(i18n, locale, "docs.items.%s.note" % doc["id"])

        faq = i18n[locale]["faq"]["items"]
        require(len(faq) >= 1, "i18n.%s.faq.items must not be empty" % locale)
        for entry in faq:
            for field in ("id", "q", "a"):
                require(field in entry, "i18n.%s.faq item missing %r" % (locale, field))
            require("<" not in entry["a"], "faq answers must be plain text (no markup): %s/%s" % (locale, entry["id"]))

    english_ids = [entry["id"] for entry in i18n["en"]["faq"]["items"]]
    for locale in locales:
        other = [entry["id"] for entry in i18n[locale]["faq"]["items"]]
        require(other == english_ids, "faq item ids must match across locales (en vs %s)" % locale)


